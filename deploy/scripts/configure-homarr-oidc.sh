#!/usr/bin/env bash
# Point Homarr at tinyauth for sign-in.
#
# Homarr keeps its own credential store, so guarding the perimeter with
# forward auth still left a second login behind the gate. Accepting an OIDC
# token from tinyauth makes one sign-in cover both.
#
# Written as a compose override rather than an edit to the stack's own file,
# so the change is reversible by deleting one file and is not lost when that
# file is next edited by hand.
set -euo pipefail

STACK_DIR=${STACK_DIR:-/srv/docker}
OVERRIDE="$STACK_DIR/docker-compose.override.yml"
SECRET_FILE=${SECRET_FILE:-/etc/command-center/oidc/homarr-client-secret}
CA_SOURCE=/var/lib/caddy/caddy/pki/authorities/local/root.crt
# Caddy writes its root 0600 root:root. Homarr's process is not root, so
# mounting it directly leaves NODE_EXTRA_CA_CERTS pointing at a file the app
# cannot open, and Node ignores it without complaint: discovery then fails
# with UNABLE_TO_GET_ISSUER_CERT_LOCALLY. Publish a readable copy instead.
CA=/etc/command-center/oidc/caddy-root.crt
ISSUER=https://auth.192.168.1.171.sslip.io:3443
AUTH_HOST=auth.192.168.1.171.sslip.io

[[ -f "$SECRET_FILE" ]] || { echo "missing $SECRET_FILE; run cc-deploy sso-v5" >&2; exit 1; }
[[ -f "$CA_SOURCE" ]] || { echo "missing Caddy root CA at $CA_SOURCE" >&2; exit 1; }
install -m 0644 "$CA_SOURCE" "$CA"

# Known limitation, deliberately not worked around here.
#
# NODE_EXTRA_CA_CERTS is set below but the HTTP stack the OIDC client uses
# does not honour it, so discovery fails with
# UNABLE_TO_GET_ISSUER_CERT_LOCALLY even with the file present and readable
# by the app user. Routing Node through OpenSSL with SSL_CERT_FILE is not an
# option either: this image's entrypoint treats any variable ending in _FILE
# as a Docker secret and exports the file's contents as a value, so a
# certificate bundle there crash-loops the container on startup.
#
# What remains is giving the issuer a publicly trusted certificate. Until
# then Homarr keeps its own login and the credential is asked for twice.

cat >"$OVERRIDE" <<YAML
# Generated by deploy/scripts/configure-homarr-oidc.sh. Delete this file and
# recreate the container to go back to Homarr's own login.
services:
  homarr:
    environment:
      # credentials stays enabled as a way back in if the provider is down.
      # Remove it once the OIDC path has been exercised for a while.
      - AUTH_PROVIDERS=credentials,oidc
      - AUTH_OIDC_ISSUER=$ISSUER
      - AUTH_OIDC_CLIENT_ID=homarr
      - AUTH_OIDC_CLIENT_SECRET=$(cat "$SECRET_FILE")
      - AUTH_OIDC_CLIENT_NAME=Command Center
      # The issuer's certificate comes from Caddy's internal CA, which Node
      # does not trust by default; without this, discovery fails at TLS.
      - NODE_EXTRA_CA_CERTS=/certs/caddy-root.crt
    volumes:
      - $CA:/certs/caddy-root.crt:ro
    # Reaching Caddy by IP presents no matching SNI and the handshake is
    # refused, so the hostname has to resolve to the bridge address.
    extra_hosts:
      - "$AUTH_HOST:172.17.0.1"
YAML

chmod 0640 "$OVERRIDE"
echo "wrote $OVERRIDE"

docker compose -f "$STACK_DIR/docker-compose.yml" -f "$OVERRIDE" up -d homarr
echo "waiting for homarr"
for _ in $(seq 1 30); do
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 http://127.0.0.1:7575/ || true)
  [[ "$code" == "200" || "$code" == "302" ]] && break
  sleep 3
done
echo "homarr http: ${code:-none}"

# Homarr fetching discovery is the step that fails if the CA or the hostname
# mapping is wrong, and it fails silently into a login page. Check it through
# Node: NODE_EXTRA_CA_CERTS applies only there, so curl or wget consult the
# system trust store and report a handshake failure that does not apply.
# docker exec defaults to root, which can read the CA even when the app
# cannot, so assert readability as the user the server actually runs as.
app_user=$(docker exec homarr sh -c \
  "ps -o user= -p \$(pgrep -f 'node.*server' | head -1) 2>/dev/null" | tr -d ' ')
app_user=${app_user:-root}
echo "homarr server runs as: $app_user"
if ! docker exec -u "$app_user" homarr sh -c "test -r /certs/caddy-root.crt"; then
  echo "FAILED: $app_user cannot read the mounted CA; Node will ignore it" >&2
  exit 1
fi

echo -n "homarr can reach the issuer: "
docker exec -u "$app_user" homarr node -e '
fetch(process.env.AUTH_OIDC_ISSUER + "/.well-known/openid-configuration")
  .then((r) => r.json())
  .then((d) => console.log("ok, issuer=" + d.issuer))
  .catch((e) => {
    console.log("FAILED " + e.message + " " + (e.cause && e.cause.code));
    process.exit(1);
  });
'
